#!/usr/bin/env node
/**
 * Morte voice for OpenPets: Claude Code hook -> Morte-flavored speech bubble and game voice bark.
 * Replaces the OpenPets-managed Claude hooks. No dependencies. Never fails the hook (always exit 0).
 *
 * node morte-hook.js                 read a Claude Code hook payload on stdin (normal use)
 * node morte-hook.js --test <cat>    fire one category by hand: thinking editing testing running
 *                                    permission question idle success error   (ignores cooldowns)
 * node morte-hook.js --check         validate every line against OpenPets' message rules
 */
"use strict";
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const net = require("node:net");
const crypto = require("node:crypto");
const { spawn } = require("node:child_process");

const DIR = __dirname;
const readJson = (p, fallback) => { try { return JSON.parse(fs.readFileSync(p, "utf8")); } catch { return fallback; } };

const LINES = readJson(path.join(DIR, "lines.json"), {});
const CLIPS = readJson(path.join(DIR, "clips.json"), { clips: {} });
const CLIP_META = readJson(path.join(DIR, "clips.meta.json"), {}); // generated by extract_voice.py (durations)
const DEFAULTS = {
  speech: true,
  audio: true,
  // chance a bark plays for each category (bubbles always show, subject to cooldown)
  audioChance: { thinking: 0.2, editing: 0, testing: 0.3, running: 0, permission: 1, question: 1, idle: 1, success: 0.7, error: 1 },
  // minimum gap between two bubbles of the same category
  cooldownMs: { thinking: 20000, editing: 20000, testing: 20000, running: 20000, permission: 3000, question: 3000, idle: 60000, success: 4000, error: 4000 },
};
// config.json overrides per key; the two per-category maps merge, so {"audioChance": {"success": 0.3}} touches only success.
const USER = readJson(process.env.MORTE_CONFIG || path.join(DIR, "config.json"), {});
const CONFIG = {
  ...DEFAULTS,
  ...USER,
  audioChance: { ...DEFAULTS.audioChance, ...(USER.audioChance || {}) },
  cooldownMs: { ...DEFAULTS.cooldownMs, ...(USER.cooldownMs || {}) },
};

const REACTION = { thinking: "thinking", editing: "editing", testing: "testing", running: "running", permission: "waiting", question: "waving", idle: "waving", success: "success", error: "error" };
const CLIP_SET = { thinking: "thinking", editing: "working", testing: "working", running: "working", permission: "permission", question: "question", idle: "idle", success: "success", error: "error" };

const STATE_DIR = process.platform === "win32"
  ? path.join(process.env.LOCALAPPDATA || path.join(os.homedir(), "AppData", "Local"), "MorteVoice")
  : path.join(process.env.XDG_STATE_HOME || path.join(os.homedir(), ".local", "state"), "morte-voice");
const STATE_PATH = path.join(STATE_DIR, "state.json");
const debug = (...a) => {
  if (process.env.MORTE_DEBUG !== "1") return;
  try { fs.mkdirSync(STATE_DIR, { recursive: true }); fs.appendFileSync(path.join(STATE_DIR, "debug.log"), `${new Date().toISOString()} ${a.join(" ")}\n`); } catch {}
};

// ---- event -> category -------------------------------------------------------------------
const TEST_RE = /\b(test|tests|vitest|jest|pytest|phpunit|pest|mocha|npm\s+test|pnpm\s+test|yarn\s+test|cargo\s+test|go\s+test|dotnet\s+test)\b/i;
function categorize(p) {
  switch (p.hook_event_name) {
    case "UserPromptSubmit": return "thinking";
    case "PermissionRequest": return "permission";
    case "Stop": return "success";
    case "StopFailure": return "error";
    case "PreToolUse": {
      const tool = String(p.tool_name || "");
      if (tool === "AskUserQuestion") return "question";
      if (/^(Edit|Write|MultiEdit|NotebookEdit)$/.test(tool)) return "editing";
      if (tool === "Bash" || tool === "PowerShell") {
        const cmd = String((p.tool_input && p.tool_input.command) || "").slice(0, 300);
        return TEST_RE.test(cmd) ? "testing" : "running";
      }
      return null;
    }
    case "Notification": {
      const type = String(p.notification_type || "");
      const msg = String(p.message || "");
      if (type === "permission_prompt" || /permission/i.test(msg)) return "permission"; // deduped by the 3 s cooldown
      if (type === "idle_prompt" || /waiting for your input/i.test(msg)) return "idle";
      return null;
    }
    default: return null;
  }
}

// ---- OpenPets message rules (mirrors desktop validateSayMessage) ---------------------------
function validMessage(m) {
  return typeof m === "string" && m.trim().length >= 1 && m.length <= 140
    && !/[\r\n]/.test(m)
    && !/```|<script|function\s+\w+|=>|\b(class|import|export|const|let|var)\b/.test(m)
    && !/https?:\/\/|www\.|\/[\w.-]+\/[\w./-]+|[A-Za-z]:\\/.test(m)
    && !/(api[_-]?key|secret|token|password|passwd|BEGIN [A-Z ]+PRIVATE KEY)/i.test(m);
}

// ---- state / picking -----------------------------------------------------------------------
const loadState = () => readJson(STATE_PATH, {});
function saveState(s) { try { fs.mkdirSync(STATE_DIR, { recursive: true }); fs.writeFileSync(STATE_PATH, JSON.stringify(s)); } catch {} }

// random pick that avoids the last few picks from the same pool
function pick(pool, recent) {
  if (!pool || pool.length === 0) return null;
  const avoid = new Set((recent || []).slice(-Math.min(3, pool.length - 1)));
  const options = pool.filter((x) => !avoid.has(x));
  return (options.length ? options : pool)[Math.floor(Math.random() * (options.length || pool.length))];
}

// ---- OpenPets IPC (pet.say on the default pet, no lease) -----------------------------------
function discoveryPath() {
  if (process.env.OPENPETS_DISCOVERY_FILE) return process.env.OPENPETS_DISCOVERY_FILE;
  if (process.platform === "win32") return path.join(process.env.APPDATA || path.join(os.homedir(), "AppData", "Roaming"), "OpenPets", "runtime", "ipc.json");
  if (process.platform === "darwin") return path.join(os.homedir(), "Library", "Application Support", "OpenPets", "runtime", "ipc.json");
  return path.join(process.env.XDG_CONFIG_HOME || path.join(os.homedir(), ".config"), "OpenPets", "runtime", "ipc.json");
}

function petSay(message, reaction) {
  return new Promise((resolve) => {
    const d = readJson(discoveryPath(), null);
    if (!d || typeof d.endpoint !== "string" || typeof d.token !== "string") { debug("no discovery"); return resolve(false); }
    let target;
    const tcp = /^tcp:\/\/([^:/]+):(\d+)$/.exec(d.endpoint);
    if (tcp) target = { host: tcp[1], port: Number(tcp[2]) };
    else target = d.endpoint;
    const req = JSON.stringify({ id: crypto.randomUUID(), version: 1, token: d.token, method: "pet.say", params: { message, reaction } }) + "\n";
    const sock = net.createConnection(target);
    let buf = "", done = false;
    const finish = (ok, why) => { if (done) return; done = true; clearTimeout(t); sock.destroy(); if (why) debug("say:", why); resolve(ok); };
    const t = setTimeout(() => finish(false, "timeout"), 2000);
    sock.setEncoding("utf8");
    sock.once("connect", () => sock.write(req));
    sock.on("data", (c) => {
      buf += c;
      const nl = buf.indexOf("\n");
      if (nl < 0) return;
      try { const r = JSON.parse(buf.slice(0, nl)); finish(r.ok === true, r.ok ? null : JSON.stringify(r.error)); } catch (e) { finish(false, String(e)); }
    });
    sock.once("error", (e) => finish(false, e.message));
  });
}

// ---- audio ---------------------------------------------------------------------------------
function play(file) {
  try {
    let cmd, args;
    if (process.platform === "win32") {
      const ps = `(New-Object System.Media.SoundPlayer '${file.replace(/'/g, "''")}').PlaySync()`;
      cmd = "powershell.exe"; args = ["-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-WindowStyle", "Hidden", "-Command", ps];
    } else if (process.platform === "darwin") { cmd = "afplay"; args = [file]; }
    else { cmd = "paplay"; args = [file]; }
    const child = spawn(cmd, args, { detached: true, stdio: "ignore", windowsHide: true });
    child.on("error", (e) => debug("audio:", e.message));
    child.unref();
  } catch (e) { debug("audio:", e.message); }
}

// ---- main ----------------------------------------------------------------------------------
async function fire(cat, { force = false } = {}) {
  const now = Date.now();
  const st = loadState();
  st.last = st.last || {}; st.recentLines = st.recentLines || {}; st.recentClips = st.recentClips || {};
  const cooldown = (CONFIG.cooldownMs || {})[cat] ?? 15000;
  if (!force && now - (st.last[cat] || 0) < cooldown) { debug("cooldown", cat); return; }
  st.last[cat] = now;

  const line = pick((LINES[cat] || []).filter(validMessage), st.recentLines[cat]);
  if (line) st.recentLines[cat] = [...(st.recentLines[cat] || []), line].slice(-5);

  let clip = null;
  const muted = process.env.MORTE_MUTE === "1" || CONFIG.audio === false;
  const chance = force ? 1 : ((CONFIG.audioChance || {})[cat] ?? 0);
  // don't talk over ourselves: skip a bark if the previous one is still playing
  const busy = !force && now < (st.audioUntil || 0);
  if (!muted && !busy && Math.random() < chance) {
    const set = CLIP_SET[cat];
    clip = pick((CLIPS.clips[set] || []).filter((c) => fs.existsSync(path.join(DIR, "clips", `${c}.wav`))), st.recentClips[set]);
    if (clip) {
      st.recentClips[set] = [...(st.recentClips[set] || []), clip].slice(-4);
      st.audioUntil = now + 600 + 1000 * ((CLIP_META[clip] || {}).dur || 1);
    }
  }
  saveState(st);

  if (clip) play(path.join(DIR, "clips", `${clip}.wav`));
  if (line && CONFIG.speech !== false) await petSay(line, REACTION[cat]);
  debug("fired", cat, JSON.stringify(line), clip || "-");
}

function readStdin(ms) {
  return new Promise((resolve) => {
    let data = "";
    const t = setTimeout(() => resolve(data), ms);
    process.stdin.setEncoding("utf8");
    process.stdin.on("data", (c) => { data += c; });
    process.stdin.on("end", () => { clearTimeout(t); resolve(data); });
    process.stdin.on("error", () => { clearTimeout(t); resolve(data); });
  });
}

async function main() {
  const argv = process.argv.slice(2);
  if (argv[0] === "--check") {
    let bad = 0;
    for (const [cat, pool] of Object.entries(LINES)) for (const l of pool) if (!validMessage(l)) { bad++; console.log(`REJECTED [${cat}] ${l}`); }
    console.log(bad ? `${bad} line(s) would be rejected by OpenPets` : "all lines pass OpenPets validation");
    process.exitCode = bad ? 1 : 0;
    return;
  }
  if (argv[0] === "--test") {
    const cat = argv[1];
    if (!REACTION[cat]) { console.log(`categories: ${Object.keys(REACTION).join(", ")}`); return; }
    await fire(cat, { force: true });
    console.log(`fired ${cat}`);
    return;
  }
  const raw = await readStdin(1500);
  let payload = {};
  try { payload = JSON.parse(raw || "{}"); } catch {}
  const cat = categorize(payload);
  debug("event", payload.hook_event_name, "->", cat);
  if (cat) await fire(cat);
}

main().catch((e) => debug("fatal", e && e.stack)).finally(() => { if (process.exitCode === undefined) process.exitCode = 0; });
